-- ZERO-COST FUNCTIONAL PILOT
-- Run this in a Snowflake trial account that has NO payment method attached.
-- Trial accounts do not support Openflow. These rows simulate Openflow's target shape.

USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE RESOURCE MONITOR FLOWPROOF_PILOT_MONITOR
  WITH CREDIT_QUOTA = 1
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 50 PERCENT DO NOTIFY
    ON 75 PERCENT DO SUSPEND
    ON 90 PERCENT DO SUSPEND_IMMEDIATE;

CREATE OR REPLACE WAREHOUSE FLOWPROOF_PILOT_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 120
  COMMENT = 'Short-lived FlowProof free-trial pilot';

ALTER WAREHOUSE FLOWPROOF_PILOT_WH
  SET RESOURCE_MONITOR = FLOWPROOF_PILOT_MONITOR;

CREATE DATABASE IF NOT EXISTS FLOWPROOF_PILOT;
CREATE SCHEMA IF NOT EXISTS FLOWPROOF_PILOT.RAW;

CREATE OR REPLACE TABLE FLOWPROOF_PILOT.RAW.ORDERS (
  id NUMBER(38, 0) NOT NULL,
  status VARCHAR(32) NOT NULL,
  amount NUMBER(12, 2) NOT NULL,
  -- PostgreSQL TIMESTAMPTZ maps to TIMESTAMP_LTZ in Snowflake Openflow.
  updated_at TIMESTAMP_LTZ NOT NULL,
  _SNOWFLAKE_INSERTED_AT TIMESTAMP_NTZ NOT NULL,
  _SNOWFLAKE_UPDATED_AT TIMESTAMP_NTZ NOT NULL,
  _SNOWFLAKE_DELETED BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (id)
);

