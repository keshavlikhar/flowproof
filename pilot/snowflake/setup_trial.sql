CREATE ROLE IF NOT EXISTS FLOWPROOF_READER;

-- Replace this password before executing the statement.
CREATE USER IF NOT EXISTS FLOWPROOF_READER
  PASSWORD = 'REPLACE_WITH_A_STRONG_UNIQUE_PASSWORD'
  DEFAULT_ROLE = FLOWPROOF_READER
  DEFAULT_WAREHOUSE = FLOWPROOF_PILOT_WH
  DEFAULT_NAMESPACE = FLOWPROOF_PILOT.RAW
  MUST_CHANGE_PASSWORD = FALSE;

ALTER USER FLOWPROOF_READER SET TIMEZONE = 'UTC';
GRANT ROLE FLOWPROOF_READER TO USER FLOWPROOF_READER;
GRANT USAGE ON WAREHOUSE FLOWPROOF_PILOT_WH TO ROLE FLOWPROOF_READER;
GRANT USAGE ON DATABASE FLOWPROOF_PILOT TO ROLE FLOWPROOF_READER;
GRANT USAGE ON SCHEMA FLOWPROOF_PILOT.RAW TO ROLE FLOWPROOF_READER;
GRANT SELECT ON TABLE FLOWPROOF_PILOT.RAW.ORDERS TO ROLE FLOWPROOF_READER;

ALTER WAREHOUSE FLOWPROOF_PILOT_WH SUSPEND;
